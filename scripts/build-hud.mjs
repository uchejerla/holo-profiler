// Builds the page from hud/src into two outputs:
//  1. lib/hud/hud-html.generated.ts  the hosted page, served by app/app/route.ts after sign-in
//  2. dist/holo-profiler.html          the standalone single-file page (same as the Claude artifact), no server needed
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = f => readFileSync(join(root, 'hud/src', f), 'utf8').replace(/\n+$/, '') + '\n';
const guard = (name, s) => { if (/<\/script/i.test(s)) throw new Error(`${name} contains a closing script tag`); return s; };
const js = f => guard(f, src(f));

const core = src('shell-head.html') + js('engine.js') + js('rules.js') + '</script>\n<script>\n' + js('ops.js') + js('ui-main.js') + '</script>\n<script>\n'
  + js('ui-rules.js') + '</script>\n<script>\n' + js('space.js') + '</script>\n';

// Standalone page: identical layout to the original build.py output.
const standalone = core + '<script>\n' + js('ui-ops.js') + '</script>\n';
mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist/holo-profiler.html'), standalone);

// Hosted page: document head, injected config, bridge, the same page, data sources UI, hosted styles.
const before = '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1">\n<script>window.__HOLO_CONFIG = ';
const after = ';</script>\n<script>\n' + js('server-bridge.js') + '</script>\n' + core
  + '<script>\n' + js('ui-sources.js') + '</script>\n<script>\n' + js('ui-ops.js') + '</script>\n<style>\n' + src('hosted.css') + '</style>\n';
mkdirSync(join(root, 'lib/hud'), { recursive: true });
writeFileSync(join(root, 'lib/hud/hud-html.generated.ts'),
  '// Generated by scripts/build-hud.mjs from hud/src. Do not edit; edit hud/src and run `npm run hud`.\n'
  + 'export const HUD_BEFORE = ' + JSON.stringify(before) + ';\n'
  + 'export const HUD_AFTER = ' + JSON.stringify(after) + ';\n');
console.log(`hud: hosted ${(before.length + after.length) / 1024 | 0} KB, standalone ${standalone.length / 1024 | 0} KB`);
